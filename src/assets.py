"""Asset discovery and caching for sprites and sounds.

Files are procedurally generated by ``tools/generate_assets.py`` and live in
``assets/`` (see ``assets/CREDITS.md`` for licensing). Everything degrades
gracefully: if a PNG or WAV is missing, callers fall back to the original
flat-color drawing or simply play nothing, so the game (and its tests) never
depend on binary assets being present.
"""
from pathlib import Path

import pygame

_ROOT = Path(__file__).resolve().parent.parent / "assets"
SPRITE_DIR = _ROOT / "sprites"
SOUND_DIR = _ROOT / "sounds"

_images: dict[str, pygame.Surface] = {}
_sounds: dict[str, pygame.mixer.Sound] = {}
_scaled: dict[tuple[str, tuple[int, int]], pygame.Surface] = {}


def load() -> None:
    """(Re)load every asset from disk. Call after ``pygame.init()``."""
    _images.clear()
    _sounds.clear()
    _scaled.clear()
    if SPRITE_DIR.is_dir():
        for path in SPRITE_DIR.glob("*.png"):
            try:
                image = pygame.image.load(path)
                _images[path.stem] = (
                    image.convert_alpha()
                    if pygame.display.get_init()
                    else image
                )
            except pygame.error:
                continue
    if SOUND_DIR.is_dir() and pygame.mixer.get_init():
        for path in SOUND_DIR.glob("*.wav"):
            try:
                _sounds[path.stem] = pygame.mixer.Sound(path)
            except pygame.error:
                continue


def image(key: str):
    """Loaded sprite surface for ``key`` or None when unavailable."""
    return _images.get(key)


def scaled_image(key: str, size: tuple[int, int]):
    """Sprite scaled to ``size``, cached per (sprite, size) pair."""
    image = _images.get(key)
    if image is None or size[0] <= 0 or size[1] <= 0:
        return None
    cache_key = (key, size)
    if cache_key not in _scaled:
        _scaled[cache_key] = pygame.transform.smoothscale(image, size)
    return _scaled[cache_key]


def sound(key: str):
    """Loaded sound or None when audio is unavailable."""
    return _sounds.get(key)
